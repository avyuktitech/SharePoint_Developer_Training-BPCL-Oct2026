// Rebuilds seed.sql, turning everything in sample-files into binary data for the Documents table.
// Run with: node database/build-seed.js
const fs = require('fs');
const path = require('path');

const FILES = [
  { name: 'welcome.txt', type: 'text/plain', description: 'A short introduction to this sample' },
  { name: 'release-notes.md', type: 'text/markdown', description: 'Markdown stored as binary data' },
  { name: 'regional-sales.csv', type: 'text/csv', description: 'CSV previewed as a table' },
  { name: 'settings.json', type: 'application/json', description: 'JSON configuration file' },
  { name: 'contoso-banner.svg', type: 'image/svg+xml', description: 'Sample image stored in the database' },
  { name: 'product-badge.svg', type: 'image/svg+xml', description: 'Second sample image' }
];

const dir = path.join(__dirname, 'sample-files');
const rows = FILES.map(file => {
  const hex = fs.readFileSync(path.join(dir, file.name)).toString('hex').toUpperCase();
  return `(N'${file.name}', N'${file.type}', N'${file.description}', 0x${hex})`;
});

const template = fs.readFileSync(path.join(__dirname, 'schema-and-tables.sql'), 'utf8');
const seed = `${template.trimEnd()}

-- Generated by build-seed.js from the files in sample-files.
INSERT INTO dbo.Documents (FileName, ContentType, Description, Content) VALUES
${rows.join(',\n')};
`;
fs.writeFileSync(path.join(__dirname, 'seed.sql'), seed);
console.log(`seed.sql written with ${FILES.length} files.`);
